#include "losu_api.h"
#include "losu_base.h"

int
main (int argc, char **argv)
{
  if (argc < 2)
    {
      losu_base_io_printf ("Usage: %s <script>\n", argv[0]);
      return 0;
    }
  losu_vm_t vm = losu_api_vm_init (0);
  assert (vm != NULL);
  struct losu_object_t script_main;
  int ret = losu_api_io_loadfile (vm, &script_main, argv[1]);
  if (ret != 0)
    return ret;
  struct losu_object_t thobj = losu_api_obj_thread_new (vm, script_main, 1024);
  losu_api_obj_thread_setstatus (vm, thobj,
                                 losu_obj_thread_status_enum_t_ready);
  losu_api_vm_mainloop (vm);
  losu_api_vm_deinit (vm);
  return 0;
}
